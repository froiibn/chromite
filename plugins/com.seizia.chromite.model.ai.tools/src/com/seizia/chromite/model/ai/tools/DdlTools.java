/**
 * DDL tools: preview (READ) and run ({@code changeSchema}, WRITE/DANGEROUS per call) create/alter/drop of tables, views and
 * indexes, per database family.
 *
 * 설계:
 * <ul>
 *     <li>DDL은 모델이 준 구조(열 정의 JSON, 열 목록)에서 DB 종류별 문법으로 만든다. 다른 점: 식별 열(SQL Server {@code IDENTITY}, MySQL
 *     {@code AUTO_INCREMENT}, PostgreSQL·Oracle {@code GENERATED BY DEFAULT AS IDENTITY}), 열 이름 바꾸기(SQL Server {@code sp_rename}),
 *     형식 바꾸기({@code ALTER COLUMN}/{@code TYPE}/{@code MODIFY}), 인덱스 지우기({@code DROP INDEX ... ON t} 또는 스키마 이름), 뷰 바꾸기
 *     ({@code CREATE OR ALTER}/{@code CREATE OR REPLACE}). 식별자는 방언 따옴표, 형식·기본값은 {@link AgentNames#checkType},
 *     {@link AgentNames#checkExpression}으로 검사한다.</li>
 *     <li>실행 전에 확인 요청에 만든 DDL 전체를 보인다({@link AIToolPreviewProvider}). {@code previewDdl}(26.1.0 전 {@code generateDdl})은 같은 DDL을 실행하지 않고 돌려준다.</li>
 *     <li>뷰의 SELECT는 읽기라고 증명되어야 한다(뷰를 만들며 다른 문장을 끼워 넣지 못하게).</li>
 *     <li>MySQL/MariaDB·Oracle에서 DDL은 열린 트랜잭션을 암묵적으로 커밋하므로 에이전트 트랜잭션이 열려 있으면 실행기가 Commit / Roll back / Cancel을 묻는다.</li>
 *     <li>26.1.0에서 작업마다 하나였던 도구 7개를 {@code changeSchema(operation)} 하나로 합쳤다(옛 ID는 별칭으로 그 작업을 고른다). 분류는 호출마다
 *     작업으로 정한다({@link #classify}): 지우기(dropTable, dropView, dropIndex)는 DANGEROUS, 나머지는 WRITE. 정적 분류(WRITE)보다 낮아지지 않고, 모르는 작업은 DANGEROUS로 본다.
 *     미리 보기는 따로 둔 READ 도구 {@code previewDdl}이다. 합친 도구 안의 미리 보기 모드로 두면 운영·읽기 전용 연결에서 WRITE로 막히거나, 분류를
 *     호출마다 낮춰야 해서(분류기는 올리기만 한다) 나눴다.</li>
 * </ul>
 *
 * 변경 이력:
 * - 2026-11-07 최초 작성
 * - 2026-11-15 도구 정리(docs/chromite/ai-agent.md "별칭"): generateDdl → previewDdl, 작업별 도구 7개를 changeSchema 하나로 합치고 호출마다
 *   분류함({@link #classify}), 열 형식 인수 type → columnType. dropIndex는 WRITE에서 DANGEROUS로(runSql이 모든 DROP을 DANGEROUS로 보는 것과 같게),
 *   MCP 힌트용 가장 높은 분류
 */
public class DdlTools extends AgentTool implements AIToolAccessClassifier, AIToolPreviewProvider, AIToolTransactionGuard {

    private static final String PREVIEW = "previewDdl"; //$NON-NLS-1$
    private static final String PARAM_OPERATION = "operation"; //$NON-NLS-1$

    @NotNull
    @Override
    protected JsonElement call(
        @NotNull AIToolCallContext context,
        @NotNull String toolId,
        @NotNull Map<String, Object> args
    ) throws DBException {
        DBPDataSourceContainer container = requireConnection(context);
        String operation = AgentArgs.require(args, PARAM_OPERATION);
        List<String> statements = generate(context, container, operation, args);
        JsonObject json = new JsonObject();
        json.addProperty("operation", operation);
        json.addProperty("sql", String.join(";\n", statements));
        if (toolId.equals(PREVIEW)) {
            json.addProperty("executed", false);
            return json;
        }
        JsonObject result = AgentSql.run(context.getMonitor(), container, AgentArgs.getString(args, "database"), AgentSql.Mode.NATIVE,
            (connection, runner) -> {
                JsonObject r = new JsonObject();
                for (String statement : statements) {
                    r = runner.execute(connection, statement, null, AgentLimits.of(Map.of(), 20), true);
                }
                return r;
            });
        json.addProperty("executed", true);
        if (result.has("messages")) {
            json.add("messages", result.get("messages"));
        }
        QueryTools.addTransactionState(container, json);
        return json;
    }

    @NotNull
    private static List<String> generate(
        @NotNull AIToolCallContext context,
        @NotNull DBPDataSourceContainer container,
        @NotNull String operation,
        @NotNull Map<String, Object> args
    ) throws DBException {
        DBPDataSource dataSource = AgentSql.connect(context.getMonitor(), container);
        DbFamily family = DbFamily.of(container);
        return AgentSql.run(context.getMonitor(), container, AgentArgs.getString(args, "database"), AgentSql.Mode.READ_ONLY,
            (connection, runner) -> switch (operation) {
                case "createTable" -> List.of(createTable(connection, dataSource, family, args));
                case "alterTable" -> List.of(alterTable(connection, dataSource, family, args));
                case "dropTable" -> List.of("DROP TABLE " + name(connection, family, args, "table").quoted(dataSource));
                case "createView" -> List.of(createView(connection, dataSource, family, args));
                case "dropView" -> List.of("DROP VIEW " + name(connection, family, args, "view").quoted(dataSource));
                case "createIndex" -> List.of(createIndex(connection, dataSource, family, args));
                case "dropIndex" -> List.of(dropIndex(connection, dataSource, family, args));
                default -> throw new AIToolArgumentException("Unknown DDL operation '" + operation +
                    "' (createTable, alterTable, dropTable, createView, dropView, createIndex, dropIndex)");
            });
    }

    @NotNull
    private static AgentNames.QName name(
        @NotNull Connection connection,
        @NotNull DbFamily family,
        @NotNull Map<String, Object> args,
        @NotNull String argument
    ) throws SQLException, AIToolArgumentException {
        return AgentNames.resolve(connection, family, AgentArgs.require(args, argument));
    }

    @NotNull
    private static String createTable(
        @NotNull Connection connection,
        @NotNull DBPDataSource dataSource,
        @NotNull DbFamily family,
        @NotNull Map<String, Object> args
    ) throws SQLException, AIToolArgumentException {
        AgentNames.QName table = name(connection, family, args, "table");
        JsonElement columns = AgentArgs.getJson(args, "columns");
        if (columns == null || !columns.isJsonArray() || columns.getAsJsonArray().isEmpty()) {
            throw new AIToolArgumentException("Argument 'columns' must be a JSON array of {name, type, nullable, default, identity}");
        }
        StringBuilder sql = new StringBuilder("CREATE TABLE ").append(table.quoted(dataSource)).append(" (\n");
        List<String> parts = new ArrayList<>();
        for (JsonElement c : columns.getAsJsonArray()) {
            if (!c.isJsonObject()) {
                throw new AIToolArgumentException("Each column must be a JSON object");
            }
            parts.add("    " + columnDefinition(dataSource, family, c.getAsJsonObject(), true));
        }
        List<String> primaryKey = AgentArgs.getList(args, "primaryKey");
        if (!primaryKey.isEmpty()) {
            parts.add("    CONSTRAINT " + DBUtils.getQuotedIdentifier(dataSource, "pk_" + table.name()) + " PRIMARY KEY (" +
                quoteList(dataSource, primaryKey) + ")");
        }
        return sql.append(String.join(",\n", parts)).append("\n)").toString();
    }

    @NotNull
    private static String columnDefinition(
        @NotNull DBPDataSource dataSource,
        @NotNull DbFamily family,
        @NotNull JsonObject column,
        boolean allowIdentity
    ) throws AIToolArgumentException {
        String name = string(column, "name");
        String type = string(column, "type");
        if (name == null || type == null) {
            throw new AIToolArgumentException("A column needs 'name' and 'type'");
        }
        StringBuilder text = new StringBuilder(DBUtils.getQuotedIdentifier(dataSource, name)).append(' ').append(AgentNames.checkType(type));
        boolean identity = allowIdentity && column.has("identity") && column.get("identity").getAsBoolean();
        if (identity) {
            text.append(switch (family) {
                case SQLSERVER -> " IDENTITY(1,1)";
                case MYSQL, MARIADB -> " AUTO_INCREMENT";
                default -> " GENERATED BY DEFAULT AS IDENTITY";
            });
        }
        String def = string(column, "default");
        if (def != null && !identity) {
            text.append(" DEFAULT ").append(AgentNames.checkExpression(def));
        }
        if (column.has("nullable") && !column.get("nullable").getAsBoolean() || identity) {
            text.append(" NOT NULL");
        }
        return text.toString();
    }

    @NotNull
    private static String alterTable(
        @NotNull Connection connection,
        @NotNull DBPDataSource dataSource,
        @NotNull DbFamily family,
        @NotNull Map<String, Object> args
    ) throws SQLException, AIToolArgumentException {
        AgentNames.QName table = name(connection, family, args, "table");
        String action = AgentArgs.require(args, "action");
        String column = AgentArgs.require(args, "column");
        String quotedTable = table.quoted(dataSource);
        String quotedColumn = DBUtils.getQuotedIdentifier(dataSource, column);
        switch (action) {
            case "addColumn" -> {
                JsonObject definition = new JsonObject();
                definition.addProperty("name", column);
                definition.addProperty("type", AgentArgs.require(args, "columnType"));
                if (args.get("nullable") != null) {
                    definition.addProperty("nullable", AgentArgs.getBoolean(args, "nullable", true));
                }
                String def = AgentArgs.getString(args, "default");
                if (def != null) {
                    definition.addProperty("default", def);
                }
                return "ALTER TABLE " + quotedTable + " ADD " + columnDefinition(dataSource, family, definition, false);
            }
            case "dropColumn" -> {
                return "ALTER TABLE " + quotedTable + " DROP COLUMN " + quotedColumn;
            }
            case "renameColumn" -> {
                String newName = AgentArgs.require(args, "newName");
                if (family == DbFamily.SQLSERVER) {
                    return "EXEC sp_rename " + SQLUtils.quoteString(dataSource, table.display() + "." + column) + ", " +
                        SQLUtils.quoteString(dataSource, newName) + ", 'COLUMN'";
                }
                return "ALTER TABLE " + quotedTable + " RENAME COLUMN " + quotedColumn + " TO " + DBUtils.getQuotedIdentifier(dataSource, newName);
            }
            case "alterColumnType" -> {
                String type = AgentNames.checkType(AgentArgs.require(args, "columnType"));
                Boolean nullable = args.get("nullable") == null ? null : AgentArgs.getBoolean(args, "nullable", true);
                String nullText = nullable == null ? "" : nullable ? " NULL" : " NOT NULL";
                return switch (family) {
                    case SQLSERVER -> "ALTER TABLE " + quotedTable + " ALTER COLUMN " + quotedColumn + " " + type + nullText;
                    case MYSQL, MARIADB -> "ALTER TABLE " + quotedTable + " MODIFY COLUMN " + quotedColumn + " " + type + nullText;
                    case ORACLE -> "ALTER TABLE " + quotedTable + " MODIFY (" + quotedColumn + " " + type + nullText + ")";
                    default -> "ALTER TABLE " + quotedTable + " ALTER COLUMN " + quotedColumn + " TYPE " + type +
                        (nullable == null ? "" : ", ALTER COLUMN " + quotedColumn + (nullable ? " DROP NOT NULL" : " SET NOT NULL"));
                };
            }
            default -> throw new AIToolArgumentException("Unknown action '" + action + "' (addColumn, dropColumn, renameColumn, alterColumnType)");
        }
    }

    @NotNull
    private static String createView(
        @NotNull Connection connection,
        @NotNull DBPDataSource dataSource,
        @NotNull DbFamily family,
        @NotNull Map<String, Object> args
    ) throws SQLException, AIToolArgumentException {
        AgentNames.QName view = name(connection, family, args, "view");
        String select = AgentSqlClassifier.stripTrailingDelimiter(AgentArgs.require(args, "select"));
        QueryTools.requireReadOnly(dataSource, select, "createView");
        boolean replace = AgentArgs.getBoolean(args, "replace", false);
        String create = !replace ? "CREATE VIEW " : family == DbFamily.SQLSERVER ? "CREATE OR ALTER VIEW " : "CREATE OR REPLACE VIEW ";
        return create + view.quoted(dataSource) + " AS\n" + select;
    }

    @NotNull
    private static String createIndex(
        @NotNull Connection connection,
        @NotNull DBPDataSource dataSource,
        @NotNull DbFamily family,
        @NotNull Map<String, Object> args
    ) throws SQLException, AIToolArgumentException {
        AgentNames.QName table = name(connection, family, args, "table");
        String index = AgentArgs.require(args, "index");
        List<String> columns = AgentArgs.getList(args, "columns");
        if (columns.isEmpty()) {
            throw new AIToolArgumentException("Argument 'columns' is required (comma-separated, optional ASC/DESC)");
        }
        List<String> keyParts = new ArrayList<>();
        for (String column : columns) {
            String[] words = column.trim().split("\\s+");
            String direction = words.length > 1 ? words[words.length - 1].toUpperCase(Locale.ROOT) : "";
            boolean hasDirection = direction.equals("ASC") || direction.equals("DESC");
            String name = hasDirection ? column.trim().substring(0, column.trim().length() - direction.length()).trim() : column.trim();
            keyParts.add(DBUtils.getQuotedIdentifier(dataSource, name) + (hasDirection ? " " + direction : ""));
        }
        StringBuilder sql = new StringBuilder("CREATE ");
        if (AgentArgs.getBoolean(args, "unique", false)) {
            sql.append("UNIQUE ");
        }
        sql.append("INDEX ").append(DBUtils.getQuotedIdentifier(dataSource, index)).append(" ON ").append(table.quoted(dataSource))
            .append(" (").append(String.join(", ", keyParts)).append(')');
        List<String> include = AgentArgs.getList(args, "include");
        if (!include.isEmpty()) {
            if (family != DbFamily.SQLSERVER && family != DbFamily.POSTGRESQL) {
                throw new AIToolArgumentException("INCLUDE columns are supported for SQL Server and PostgreSQL only");
            }
            sql.append(" INCLUDE (").append(quoteList(dataSource, include)).append(')');
        }
        return sql.toString();
    }

    @NotNull
    private static String dropIndex(
        @NotNull Connection connection,
        @NotNull DBPDataSource dataSource,
        @NotNull DbFamily family,
        @NotNull Map<String, Object> args
    ) throws SQLException, AIToolArgumentException {
        AgentNames.QName table = name(connection, family, args, "table");
        String index = DBUtils.getQuotedIdentifier(dataSource, AgentArgs.require(args, "index"));
        return switch (family) {
            case SQLSERVER, MYSQL, MARIADB -> "DROP INDEX " + index + " ON " + table.quoted(dataSource);
            default -> "DROP INDEX " + (table.schema() == null ? "" : DBUtils.getQuotedIdentifier(dataSource, table.schema()) + ".") + index;
        };
    }

    @NotNull
    private static String quoteList(@NotNull DBPDataSource dataSource, @NotNull List<String> names) {
        List<String> quoted = new ArrayList<>();
        for (String name : names) {
            quoted.add(DBUtils.getQuotedIdentifier(dataSource, name.trim()));
        }
        return String.join(", ", quoted);
    }

    @Nullable
    private static String string(@NotNull JsonObject json, @NotNull String name) {
        JsonElement value = json.get(name);
        return value == null || value.isJsonNull() ? null : value.getAsString();
    }

    // ------------------------------------------------------------------ policy hooks

    /**
     * changeSchema: a drop is DANGEROUS (data or an object is gone; dropIndex too since 26.1.0, as runSql classifies every
     * DROP), the other operations WRITE; an operation this class does not know is DANGEROUS until the generator refuses it.
     * previewDdl only builds text: READ.
     */
    @NotNull
    @Override
    public AIToolAccess classify(@NotNull AIToolCallContext context, @NotNull Map<String, Object> arguments) {
        if (context.getTool().getId().equals(PREVIEW)) {
            return AIToolAccess.READ;
        }
        String operation = AgentArgs.getString(arguments, PARAM_OPERATION);
        return switch (operation == null ? "" : operation.trim()) {
            case "createTable", "alterTable", "createView", "createIndex" -> AIToolAccess.WRITE;
            default -> AIToolAccess.DANGEROUS;
        };
    }

    @NotNull
    @Override
    public AIToolAccess getHighestAccess(@NotNull AIFunctionDescriptor tool) {
        return tool.getId().equals(PREVIEW) ? AIToolAccess.READ : AIToolAccess.DANGEROUS;
    }

    @Nullable
    @Override
    public String getPreview(@NotNull AIToolCallContext context, @NotNull Map<String, Object> arguments) throws DBException {
        DBPDataSourceContainer container = requireConnection(context);
        return String.join(";\n", generate(context, container, AgentArgs.require(arguments, PARAM_OPERATION), arguments));
    }

    @NotNull
    @Override
    public List<AIPendingTransaction> findPendingTransactions(
        @NotNull AIToolCallContext context,
        @NotNull Map<String, Object> arguments
    ) {
        if (context.getTool().getId().equals(PREVIEW)) {
            return List.of();
        }
        // Every operation here is DDL; the statement head is what implicitCommitRisk looks at
        return QueryTools.implicitCommitRisk(context, List.of("CREATE"));
    }

    @Override
    public void resolvePendingTransactions(
        @NotNull AIToolCallContext context,
        @NotNull Map<String, Object> arguments,
        @NotNull AIToolConfirmationAnswer answer
    ) throws DBException {
        AgentSql.endTransaction(context.getMonitor(), requireConnection(context), answer == AIToolConfirmationAnswer.COMMIT);
    }
}
