package com.seizia.chromite.model;

import org.jkiss.code.NotNull;
import org.jkiss.dbeaver.DBException;
import com.seizia.chromite.model.runtime.DBRProgressMonitor;

import java.util.Map;

/**
 * Object with DDL
 *
 * 변경 이력:
 * - 2026-11-29 Chromite: {@link #OPTION_SKIP_DEFAULTS_RESTORE}. Modify 스크립트를 받는 자기 세션 쿼리 창은 개체의 DB/스키마에서 열리므로,
 *   객체 관리자가 끝에 붙이던 "실행 문맥의 기본 DB/스키마로 돌아가기" 문장이 그 창의 세션을 다른 곳으로 옮겼다
 *   (docs/chromite/swing-sql-editor-session-ui.md "주 세션을 옮기던 명령: 개체의 DB/스키마에서 여는 창")
 */
public interface DBPScriptObject extends DBPObject {

    // If object definition was cached - refresh it
    String OPTION_REFRESH = "refresh";
    // Use fully qualified names. True by default
    String OPTION_FULLY_QUALIFIED_NAMES = "useFQN";
    String OPTION_INCLUDE_OBJECT_DROP = "script.includeDrop";
    String OPTION_SCRIPT_FORMAT = "script.format";
    String OPTION_SCRIPT_FORMAT_COMPACT = "script.format.compact";
    String OPTION_SCRIPT_EXCLUDE_AUTO_GENERATED_COLUMN = "script.exclude.autogenerated.column";
    String OPTION_SCRIPT_USE_CUSTOM_DATA_FORMAT = "script.use.custom.data.format";
    String OPTION_SCRIPT_INCLUDE_VIEWS = "script.include.views";
    String OPTION_COMPOSITE_OBJECT = "composite.object"; //$NON-NLS-1$

    String OPTION_DDL_SOURCE = "ddl.source";

    // Extracts object source for debugger
    // By default the same as regular source but in some cases source should be transformed (e.g. for PG)
    String OPTION_DEBUGGER_SOURCE = "debugger.source";

    // Embedded source is used for obtaining source of
    // nested objects (columns, constraints, etc) which can be embedded in parent object declaration (tables)
    String OPTION_EMBEDDED_SOURCE = "embedded.source";

    // Means that result script will be used for object save
    String OPTION_OBJECT_SAVE = "object.save";

    // Can be used by DDL generators to generate object ALTER but CREATE.
    String OPTION_OBJECT_ALTER = "object.alter";

    /**
     * Object managers' persist actions (Boolean, default false): the session that runs the script is to stay in the object's
     * database/schema, so leave out the last statement that switches it back to the execution context's default database/schema
     * (SQL Server {@code USE <default>}, MySQL {@code USE <default>}, Oracle {@code ALTER SESSION SET CURRENT_SCHEMA=<default>}).
     * The first switch to the object's place stays. Without it the script is self-contained: it returns the session where it was.
     */
    String OPTION_SKIP_DEFAULTS_RESTORE = "script.skipDefaultsRestore"; //$NON-NLS-1$

    String OPTION_DDL_SKIP_FOREIGN_KEYS = "ddl.skipForeignKeys"; //$NON-NLS-1$
    String OPTION_DDL_ONLY_FOREIGN_KEYS = "ddl.onlyForeignKeys"; //$NON-NLS-1$
    String OPTION_SKIP_UNIQUE_KEYS = "ddl.skipUniqueKeys"; //$NON-NLS-1$
    String OPTION_SKIP_INDEXES = "ddl.skipIndexes"; //$NON-NLS-1$
    String OPTION_SKIP_DROPS = "ddl.skipDrops"; //$NON-NLS-1$

    String OPTION_DDL_SEPARATE_FOREIGN_KEYS_STATEMENTS = "ddl.separateForeignKeys"; //$NON-NLS-1$
    String OPTION_DDL_SEPARATE_CONSTRAINT_INDEXES = "ddl.separateConstraintIndexes"; //$NON-NLS-1$

    String OPTION_INCLUDE_NESTED_OBJECTS = "ddl.includeNestedObjects"; //$NON-NLS-1$
    String OPTION_INCLUDE_COMMENTS = "ddl.includeComments"; //$NON-NLS-1$
    String OPTION_INCLUDE_PERMISSIONS = "ddl.includePermissions"; //$NON-NLS-1$
    String OPTION_INCLUDE_PARTITIONS = "ddl.includePartitions"; //$NON-NLS-1$

    String OPTION_USE_SPECIAL_NAME = "ddl.useSpecialName"; //$NON-NLS-1$

    String OPTION_CAST_PARAMS = "sql.castParameter"; //$NON-NLS-1$

    String OPTION_FORMAT_SQL = "sql.format"; //$NON-NLS-1$

    Map<String, Object> EMPTY_OPTIONS = Map.of();

    @NotNull
    String getObjectDefinitionText(@NotNull DBRProgressMonitor monitor, @NotNull Map<String, Object> options)
        throws DBException;

}
