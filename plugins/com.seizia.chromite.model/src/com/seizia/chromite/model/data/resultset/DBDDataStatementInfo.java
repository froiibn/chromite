package com.seizia.chromite.model.data.resultset;

import org.jkiss.code.NotNull;
import com.seizia.chromite.model.DBUtils;
import com.seizia.chromite.model.data.DBDAttributeValue;
import com.seizia.chromite.model.struct.DBSEntity;

import java.util.ArrayList;
import java.util.List;

public class DBDDataStatementInfo {
    protected final List<DBDAttributeValue> updateAttributes = new ArrayList<>();
    protected final List<DBDAttributeValue> keyAttributes = new ArrayList<>();
    protected final DBSEntity entity;
    protected boolean executed = false;
    private boolean keysRequired;

    public DBDDataStatementInfo(@NotNull DBSEntity entity) {
        this.entity = entity;
    }

    @NotNull
    public DBSEntity getEntity() {
        return entity;
    }

    @NotNull
    public List<DBDAttributeValue> getUpdateAttributes() {
        return updateAttributes;
    }

    @NotNull
    public List<DBDAttributeValue> getKeyAttributes() {
        return keyAttributes;
    }

    public boolean isExecuted() {
        return executed;
    }

    public void setExecuted(boolean executed) {
        this.executed = executed;
    }

    public boolean needKeys() {
        if (keysRequired) {
            return true;
        }
        for (DBDAttributeValue col : keyAttributes) {
            if (col.getAttribute().isAutoGenerated() && DBUtils.isNullValue(col.getValue())) {
                return true;
            }
        }
        return false;
    }

    public void setKeysRequired(boolean keysRequired) {
        this.keysRequired = keysRequired;
    }

}
