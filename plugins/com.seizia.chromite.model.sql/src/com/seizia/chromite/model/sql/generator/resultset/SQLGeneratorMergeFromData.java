package com.seizia.chromite.model.sql.generator.resultset;

import org.jkiss.code.NotNull;
import org.jkiss.dbeaver.DBException;
import com.seizia.chromite.model.DBUtils;
import com.seizia.chromite.model.data.DBDAttributeBinding;
import com.seizia.chromite.model.data.DBDResultSetDataProvider;
import com.seizia.chromite.model.data.DBDValueRow;
import com.seizia.chromite.model.runtime.DBRProgressMonitor;
import com.seizia.chromite.model.sql.SQLDialect;
import com.seizia.chromite.model.struct.DBSEntity;
import com.seizia.chromite.model.struct.DBSEntityAttribute;
import org.jkiss.utils.CommonUtils;

import java.util.ArrayList;
import java.util.List;

/**
 * One MERGE statement per selected row: the row's values update the table row with the same unique key, or are inserted
 * when there is none.
 *
 * 설계: 테이블 MERGE 생성기({@code SQLGeneratorMerge})는 {@code USING SOURCE_TABLE} 자리표시자를 쓰지만, 결과 행에는 값이 있으므로 원본을
 * 그 값의 {@code SELECT}({@code SELECT 1 AS id, 'a' AS name [FROM DUAL]})로 만든다. {@code VALUES} 행 생성자보다 이 형태가
 * SQL Server, Oracle, DB2 등에서 고루 통한다. 방언이 이중 테이블을 요구하면({@link SQLDialect#getDualTableName}) FROM에 넣는다.
 * 별칭 앞에 {@code AS}를 쓰지 않는다(Oracle은 테이블 별칭의 AS를 받지 않는다). ON에 쓴 키 열은 UPDATE SET에 넣지 않는다(Oracle ORA-38104).
 * 자동 생성 열(IDENTITY 등)은 UPDATE와 INSERT에서 뺀다(SQL Server는 IDENTITY 열에 값을 넣지 못함). 키가 자동 생성 열이어도 ON에는 쓴다.
 * 어떤 방언에서 제안할지는 화면이 {@link SQLDialect#supportsMergeStatement}로 정한다. 문장은 만들 뿐 실행하지 않는다.
 *
 * 변경 이력:
 * - 2026-11-08 최초 작성: 결과 행에서 SQL 만들기 (docs/chromite/swing-result-generate-sql.md)
 */
public class SQLGeneratorMergeFromData extends SQLGeneratorResultSet {

    private static final String TARGET_ALIAS = "tgt"; //$NON-NLS-1$
    private static final String SOURCE_ALIAS = "src"; //$NON-NLS-1$

    @Override
    public boolean isDMLOption() {
        return true;
    }

    @Override
    public boolean isUniqueKeyRequired() {
        return true;
    }

    @Override
    protected void generateSQL(
        @NotNull DBRProgressMonitor monitor,
        @NotNull StringBuilder sql,
        @NotNull DBDResultSetDataProvider dataProvider
    ) throws DBException {
        DBSEntity table = dataProvider.getSingleSource();
        if (table == null) {
            throw new DBException("The result has no single source table");
        }
        List<DBDAttributeBinding> keys = getKeyAttributes(monitor, dataProvider);
        if (keys.isEmpty()) {
            throw new DBException("The result has no unique key of table " + table.getName());
        }
        List<DBDAttributeBinding> columns = getTableColumns(dataProvider, table);
        for (DBDAttributeBinding key : keys) {
            if (!columns.contains(key)) {
                throw new DBException("Key column " + key.getName() + " is not a column of table " + table.getName());
            }
        }
        // The source row has the keys and the inserted columns
        List<DBDAttributeBinding> sourceColumns = new ArrayList<>();
        List<DBDAttributeBinding> updated = new ArrayList<>();
        List<DBDAttributeBinding> inserted = new ArrayList<>();
        for (DBDAttributeBinding column : columns) {
            boolean key = keys.contains(column);
            if (key || !isAutoGenerated(column)) {
                sourceColumns.add(column);
            }
            if (isAutoGenerated(column)) {
                continue;
            }
            inserted.add(column);
            if (!key) {
                updated.add(column);
            }
        }
        SQLDialect dialect = table.getDataSource().getSQLDialect();
        String dualTable = dialect.getDualTableName();
        String separator = getLineSeparator();
        for (DBDValueRow row : dataProvider.getSelectedRows()) {
            sql.append("MERGE INTO ").append(getEntityName(table)).append(' ').append(TARGET_ALIAS).append(separator);
            sql.append("USING (SELECT ");
            boolean hasColumn = false;
            for (DBDAttributeBinding column : sourceColumns) {
                if (hasColumn) {
                    sql.append(", ");
                }
                appendAttributeValue(dataProvider, sql, column, row, false);
                sql.append(" AS ").append(getColumnName(column));
                hasColumn = true;
            }
            if (!CommonUtils.isEmpty(dualTable)) {
                sql.append(" FROM ").append(dualTable);
            }
            sql.append(") ").append(SOURCE_ALIAS).append(separator);
            sql.append("ON (");
            for (int i = 0; i < keys.size(); i++) {
                if (i > 0) {
                    sql.append(" AND ");
                }
                appendPair(sql, keys.get(i), " = ");
            }
            sql.append(')').append(separator);
            if (!updated.isEmpty()) {
                sql.append("WHEN MATCHED THEN UPDATE SET ");
                for (int i = 0; i < updated.size(); i++) {
                    if (i > 0) {
                        sql.append(", ");
                    }
                    appendPair(sql, updated.get(i), " = ");
                }
                sql.append(separator);
            }
            sql.append("WHEN NOT MATCHED THEN INSERT (");
            for (int i = 0; i < inserted.size(); i++) {
                if (i > 0) {
                    sql.append(", ");
                }
                sql.append(getColumnName(inserted.get(i)));
            }
            sql.append(")").append(separator).append("VALUES (");
            for (int i = 0; i < inserted.size(); i++) {
                if (i > 0) {
                    sql.append(", ");
                }
                sql.append(SOURCE_ALIAS).append('.').append(getColumnName(inserted.get(i)));
            }
            sql.append(");\n");
        }
    }

    private static void appendPair(@NotNull StringBuilder sql, @NotNull DBDAttributeBinding column, @NotNull String operator) {
        String name = getColumnName(column);
        sql.append(TARGET_ALIAS).append('.').append(name).append(operator).append(SOURCE_ALIAS).append('.').append(name);
    }

    private static boolean isAutoGenerated(@NotNull DBDAttributeBinding column) {
        DBSEntityAttribute attribute = column.getEntityAttribute();
        return attribute != null && attribute.isAutoGenerated();
    }

    /**
     * The quoted name of the table column (the result may show it under an alias).
     */
    @NotNull
    private static String getColumnName(@NotNull DBDAttributeBinding column) {
        DBSEntityAttribute attribute = column.getEntityAttribute();
        return attribute != null ? DBUtils.getQuotedIdentifier(attribute) : DBUtils.getQuotedIdentifier(column.getDataSource(), column.getName());
    }
}
